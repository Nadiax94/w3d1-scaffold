QUEUE = [32, 32, 32, 256] * 6

import time

def static_queue(
    batch,
    prompt="Explain what an inference server does."
):

    t0 = time.time()

    useful = 0
    slots = 0


    for i in range(0, len(QUEUE), batch):

        # أخذ مجموعة بحجم batch
        chunk = QUEUE[i:i+batch]


        # أطول طلب يحدد وقت الباتش
        n = max(chunk)


        # تجهيز النصوص
        enc = tok(
            [prompt] * len(chunk),
            return_tensors="pt",
            padding=True
        ).to("cuda")


        # تشغيل التوليد
        model.generate(
            **enc,
            max_new_tokens=n,
            do_sample=False
        )


        # عدد التوكنات المفيدة
        useful += sum(chunk)


        # عدد الأماكن التي عالجتها GPU
        slots += n * len(chunk)



    dt = time.time() - t0


    return {

        "batch": batch,

        "wall_s": round(dt,2),

        "tokens_per_s":
            round(useful/dt,1),

        "slot_efficiency":
            round(useful/slots,3)

    }

batch_rows = {}

