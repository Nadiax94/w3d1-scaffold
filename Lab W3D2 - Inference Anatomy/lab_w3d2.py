import gc

def kv_formula_kb_per_token(
    layers=28,
    kv_heads=2,
    head_dim=128,
    dbytes=2
):
    return 2 * layers * kv_heads * head_dim * dbytes / 1024

formula = kv_formula_kb_per_token()

print("formula KB/token:", formula)

def cache_bytes(pkv):

    if hasattr(pkv, "key_cache"):

        tensors = list(pkv.key_cache) + list(pkv.value_cache)

    else:

        tensors = [
            t
            for layer in pkv
            for t in layer
        ]

    return sum(
        t.numel() * t.element_size()
        for t in tensors
    )

def measure_kv(context: int, new_tokens: int = 256):

    torch.cuda.empty_cache()
    gc.collect()

    torch.cuda.reset_peak_memory_stats()


    enc = tok(
        prompt_of_len(context),
        return_tensors="pt"
    ).to("cuda")


    before = torch.cuda.memory_allocated()


    out = model.generate(
        **enc,
        max_new_tokens=new_tokens,
        do_sample=False,
        use_cache=True,
        return_dict_in_generate=True
    )


    torch.cuda.synchronize()


    peak = torch.cuda.max_memory_allocated()


    total_tokens = out.sequences.shape[1]


    return {
        "context": context,

        "total_tokens": int(total_tokens),

        "peak_kb_per_token":
        round(
            (peak-before)
            / total_tokens
            /1024,
            1
        ),

        "kv_kb_per_token":
        round(
            cache_bytes(out.past_key_values)
            / total_tokens
            /1024,
            1
        )
    }

